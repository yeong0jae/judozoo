-- app_user에 내부 식별자를 주고 PK를 옮긴다.
-- 앱은 DDL을 만들지 않으므로 각 환경에 수동 적용한다(로컬·운영 각각).
--
-- 왜 — 로그 한 줄마다 "누구의 요청인가"를 남기기 시작했는데(여정 추적), 담을 식별자가
-- `google_sub`뿐이었다. 그런데 구글의 `sub`은 클라이언트별 값이 아니라 **모든 앱에 같은 값**을
-- 주는 계정 식별자다. 영구적이고 교체할 수 없으며, 다른 서비스의 데이터와 결합된다.
-- 로그·메트릭처럼 여러 곳으로 퍼지는 자리에 둘 성질이 아니다.
--
-- 그래서 테이블이 자기 식별자를 갖게 한다. `id`는 이 시스템 밖에서 아무 의미가 없어
-- 유출돼도 결합되지 않고, 필요하면 갈아끼울 수 있다. `google_sub`은 외부 계정을 잇는
-- 열로 남으며 UNIQUE라 중복 가입은 여전히 막힌다.
--
-- 되돌리려면 PK를 google_sub으로 되돌리고 id를 DROP한다. 참조하는 FK가 **0개**라
-- (코드베이스 전체에 ForeignKey가 없다) 어느 방향이든 안전하다.
--
-- **적용 순서를 지킨다 — 이 파일을 먼저 적용하고 배포한다.** 반대로 하면 로그인 경로가
-- 없는 열(id)을 읽어 실패한다.
--
-- 로컬(mysql:8.4 컨테이너)에서 3행을 넣고 실제로 돌려봤다. 한 문장으로 끝나고
-- 기존 행에는 옛 PK 순서대로 1부터 부여된다.

ALTER TABLE app_user
  DROP PRIMARY KEY,
  ADD UNIQUE KEY uk_app_user_google_sub (google_sub),
  ADD COLUMN id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY FIRST;
